# ─── Scenario 8: Prereq failure ──────────────────────────────────────────

def test_prereq_failure():
    print("\n── Scenario 8: Prereq failure (Python version too low)")
    from types import SimpleNamespace
    fake_version = SimpleNamespace(major=3, minor=10, micro=0, releaselevel="final", serial=0)
    # Make it compare as tuple for the < check
    class FakeVersion(SimpleNamespace):
        def __lt__(self, other):
            return (self.major, self.minor) < other
        def __ge__(self, other):
            return not self.__lt__(other)
    fake = FakeVersion(major=3, minor=10, micro=0, releaselevel="final", serial=0)
    with mock.patch.object(sys, "version_info", fake):
        from io import StringIO
        old_stderr = sys.stderr
        sys.stderr = StringIO()
        try:
            installer.check_prereqs()
            report("check_prereqs exits on old Python", False, "did not exit")
        except SystemExit as e:
            report("check_prereqs exits on old Python", e.code == 1)
        finally:
            sys.stderr = old_stderr


# ─── Scenario 9: Corrupted settings.json ─────────────────────────────────

def test_corrupted_settings():
    print("\n── Scenario 9: Corrupted settings.json — no data loss")
    with tempfile.TemporaryDirectory() as tmp_str:
        tmp = Path(tmp_str)

        settings_path = tmp / "settings.json"
        settings_path.write_text("{invalid json oh no")

        patches = patch_home(tmp)
        patchers = apply_patches(patches)
        try:
            # Install should still work (files copy), hook merge should fail gracefully
            from io import StringIO
            captured_err = StringIO()
            captured_out = StringIO()
            old_stderr = sys.stderr
            old_stdout = sys.stdout
            sys.stderr = captured_err
            sys.stdout = captured_out
            try:
                installer.main(["install"])
            finally:
                sys.stderr = old_stderr
                sys.stdout = old_stdout

            err_output = captured_err.getvalue()
            out_output = captured_out.getvalue()

            # Files should still be installed despite settings failure
            manifest_path = tmp / "frontier-brain" / ".manifest"
            report("files installed despite bad settings", manifest_path.exists())

            # Backup should exist
            backup_path = tmp / "settings.json.bak-frontier-brain"
            report("backup of corrupt settings made", backup_path.exists())

            # Original corrupt content preserved in backup
            if backup_path.exists():
                backup_content = backup_path.read_text()
                report("backup has original content", "invalid json" in backup_content)

            report("hook reported as FAILED", "FAILED" in out_output or "could not parse" in err_output)

        finally:
            stop_patches(patchers)


# ─── Run all ──────────────────────────────────────────────────────────────

def main():
    print("=" * 60)
    print("frontier-brain installer — End-to-End Tests")
    print("=" * 60)

    test_fresh_install()
    test_upgrade_from_legacy()
    test_upgrade_v2()
    test_same_version()
    test_force_reinstall()
    test_uninstall()
    test_uninstall_not_installed()
    test_prereq_failure()
    test_corrupted_settings()

    print("\n" + "=" * 60)
    print(f"Results: {PASS} passed, {FAIL} failed, {PASS + FAIL} total")
    if FAIL > 0:
        print("\nFailed:")
        for name, ok, detail in RESULTS:
            if not ok:
                print(f"  FAIL: {name} — {detail}")
    print("=" * 60)
    sys.exit(1 if FAIL > 0 else 0)


if __name__ == "__main__":
    main()
