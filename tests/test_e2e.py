from unittest import mock

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "installer"))

import installer.main as installer

PASS = 0
FAIL = 0
RESULTS: list[tuple[str, bool, str]] = []


def report(name: str, ok: bool, detail: str = "") -> None:
    global PASS, FAIL
    if ok:
        PASS += 1
    else:
        FAIL += 1
    RESULTS.append((name, ok, detail))
    status = "PASS" if ok else "FAIL"
    msg = f"  [{status}] {name}"
    if detail and not ok:
        msg += f" — {detail}"
    print(msg)


def patch_home(tmp: Path):
    """Return a dict of patches that redirect installer to use tmp as CLAUDE_HOME."""
    return {
        "installer.main.CLAUDE_HOME": tmp,
        "installer.main.MANIFEST_PATH": tmp / "frontier-brain" / ".manifest",
        "installer.main.SETTINGS_PATH": tmp / "settings.json",
        "installer.main.SETTINGS_BACKUP_PATH": tmp / "settings.json.bak-frontier-brain",
    }


def apply_patches(patches: dict):
    """Apply mock.patch for each key-value pair. Returns patcher list."""
    patchers = []
    for target, value in patches.items():
        p = mock.patch(target, value)
        p.start()
        patchers.append(p)
    return patchers


def stop_patches(patchers):
    for p in patchers:
        p.stop()


def count_managed_files_in(d: Path) -> int:
    """Count files, excluding __pycache__ (generated by Python runtime)."""
    if not d.exists():
        return 0
    return sum(1 for f in d.rglob("*") if f.is_file() and "__pycache__" not in f.parts)


# ─── Scenario 1: Fresh install on empty home ────────────────────────────

def test_fresh_install():
    print("\n── Scenario 1: Fresh install on empty CLAUDE_HOME")
    with tempfile.TemporaryDirectory() as tmp_str:
        tmp = Path(tmp_str)
        patches = patch_home(tmp)
        patchers = apply_patches(patches)
        try:
            installer.main(["install"])

            manifest_path = tmp / "frontier-brain" / ".manifest"
            report("manifest created", manifest_path.exists())

            manifest = json.loads(manifest_path.read_text())
            report("manifest has commit", manifest.get("commit") is not None and manifest["commit"] != "None")
            report("manifest has files", len(manifest.get("files", [])) > 0)

            expected_files = [
                tmp / "frontier-brain" / "bin" / "decision-engine.py",
                tmp / "frontier-brain" / "bin" / "visualize.py",
                tmp / "frontier-brain" / "bin" / "static" / "d3.v7.min.js",
                tmp / "frontier-brain" / "bin" / "static" / "index.html",
                tmp / "frontier-brain" / "lib" / "graphdb.py",
                tmp / "frontier-brain" / "lib" / "router.py",
                tmp / "frontier-brain" / "lib" / "frontmatter.py",
                tmp / "hooks" / "frontier-brain" / "decision-detect.py",
                tmp / "skills" / "decision-recall" / "SKILL.md",
                tmp / "skills" / "decision-record" / "SKILL.md",
                tmp / "skills" / "decision-harvest" / "SKILL.md",
                tmp / "skills" / "open-brain" / "SKILL.md",
            ]
            all_exist = all(f.exists() for f in expected_files)
            missing = [str(f.relative_to(tmp)) for f in expected_files if not f.exists()]
            report("all files installed", all_exist, f"missing: {missing}" if missing else "")

            settings_path = tmp / "settings.json"
            report("settings.json created", settings_path.exists())
            if settings_path.exists():
                settings = json.loads(settings_path.read_text())
                hooks = settings.get("hooks", {}).get("UserPromptSubmit", [])
                has_hook = any(
                    "decision-detect" in h.get("command", "")
                    for group in hooks
                    for h in group.get("hooks", [])
                )
                report("hook registered in settings", has_hook)
                hook_uses_py = any(
                    "decision-detect.py" in h.get("command", "")
                    for group in hooks
                    for h in group.get("hooks", [])
                )
                report("hook uses .py (not .js)", hook_uses_py)

            # No backup on fresh install — settings.json didn't exist before merge_hook created it
            backup_path = tmp / "settings.json.bak-frontier-brain"
            report("no backup on fresh install (correct)", not backup_path.exists())

        finally:
            stop_patches(patchers)


# ─── Scenario 2: Upgrade from legacy (no manifest, .js hook exists) ──────

def test_upgrade_from_legacy():
    print("\n── Scenario 2: Upgrade from legacy (no manifest, .js hook)")
    with tempfile.TemporaryDirectory() as tmp_str:
        tmp = Path(tmp_str)

        # Pre-seed a legacy settings.json with .js hook
        legacy_settings = {
            "hooks": {
                "UserPromptSubmit": [
                    {
                        "matcher": "",
                        "hooks": [
                            {
                                "type": "command",
                                "command": 'node "/old/path/decision-detect.js"',
                                "timeout": 5,
                            }
                        ],
                    }
                ]
            }
        }
        settings_path = tmp / "settings.json"
        settings_path.write_text(json.dumps(legacy_settings, indent=2))

        patches = patch_home(tmp)
        patchers = apply_patches(patches)
        try:
            installer.main(["install"])

            manifest_path = tmp / "frontier-brain" / ".manifest"
            report("manifest created (from legacy)", manifest_path.exists())

            settings = json.loads(settings_path.read_text())
            hooks = settings.get("hooks", {}).get("UserPromptSubmit", [])
            report("exactly one hook group", len(hooks) == 1, f"got {len(hooks)}")

            has_js = any(
                ".js" in h.get("command", "")
                for group in hooks
                for h in group.get("hooks", [])
            )
            report("old .js hook removed", not has_js)

            has_py = any(
                "decision-detect.py" in h.get("command", "")
                for group in hooks
                for h in group.get("hooks", [])
            )
            report("new .py hook registered", has_py)

        finally:
            stop_patches(patchers)


# ─── Scenario 3: Upgrade from v2 (manifest exists, different commit) ─────

def test_upgrade_v2():
    print("\n── Scenario 3: Upgrade (manifest exists, different commit)")
    with tempfile.TemporaryDirectory() as tmp_str:
        tmp = Path(tmp_str)
        patches = patch_home(tmp)
        patchers = apply_patches(patches)
        try:
            # First install
            installer.main(["install"])
            manifest_path = tmp / "frontier-brain" / ".manifest"
            old_manifest = json.loads(manifest_path.read_text())

            # Fake a different commit in manifest (simulates old version)
            old_manifest["commit"] = "aaaaaaaabbbbbbbbccccccccdddddddd00000000"
            # Add a stale file to test cleanup
            stale_file = tmp / "frontier-brain" / "lib" / "old_module.py"
            stale_file.parent.mkdir(parents=True, exist_ok=True)
            stale_file.write_text("# stale")
            old_manifest["files"].append(str(stale_file))
            manifest_path.write_text(json.dumps(old_manifest, indent=2))

            # Re-install (upgrade)
            installer.main(["install"])

            new_manifest = json.loads(manifest_path.read_text())
            report("commit updated", new_manifest["commit"] != "aaaaaaaabbbbbbbbccccccccdddddddd00000000")
            report("stale file cleaned up", not stale_file.exists())

            # All current files still exist
            missing = [f for f in new_manifest["files"] if not Path(f).exists()]
            report("all current files present after upgrade", len(missing) == 0, f"missing: {missing}")

        finally:
            stop_patches(patchers)


